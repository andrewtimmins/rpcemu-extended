/* ---- interrupts, which every core offers differently -------------------- */

static void
ops_rv32i_interrupt(uint32_t ctrl)
{
	/* Neither: this core implements no CSRs, so it has no way to accept an
	   interrupt. Saying so plainly beats a register that silently does
	   nothing. */
	(void) ctrl;
}

static void
ops_m6502_interrupt(uint32_t ctrl)
{
	if ((ctrl & OPENBUS_COPROC_IRQ_NMI) != 0) {
		cpu6502_nmi(&cp.cpu.m6502);
	} else if ((ctrl & OPENBUS_COPROC_IRQ_ASSERT) != 0) {
		(void) cpu6502_irq(&cp.cpu.m6502);
	}
}

static void
ops_z80_interrupt(uint32_t ctrl)
{
	if ((ctrl & OPENBUS_COPROC_IRQ_NMI) != 0) {
		cpu_z80_nmi(&cp.cpu.z80);
	} else if ((ctrl & OPENBUS_COPROC_IRQ_ASSERT) != 0) {
		(void) cpu_z80_interrupt(&cp.cpu.z80,
		    (uint8_t) OPENBUS_COPROC_IRQ_VECTOR(ctrl));
	}
}

/*
 * ★ The 6809 is the one core here with TWO maskable interrupt lines, so the
 * level field is not decoration for it. IRQ and FIRQ differ in how much state
 * they push, which means a handler written for one cannot serve the other, and a
 * guest that asked for the wrong one would return from it to a wrong address.
 */
static void
ops_m6809_interrupt(uint32_t ctrl)
{
	if ((ctrl & OPENBUS_COPROC_IRQ_NMI) != 0) {
		cpu6809_nmi(&cp.cpu.m6809);
	} else if ((ctrl & OPENBUS_COPROC_IRQ_ASSERT) != 0) {
		if (OPENBUS_COPROC_IRQ_LEVEL(ctrl) == 1) {
			(void) cpu6809_firq(&cp.cpu.m6809);
		} else {
			(void) cpu6809_irq(&cp.cpu.m6809);
		}
	}
}

/* The 6800 has one maskable line, so the level field means nothing to it. */
static void
ops_m6800_interrupt(uint32_t ctrl)
{
	if ((ctrl & OPENBUS_COPROC_IRQ_NMI) != 0) {
		cpu6800_nmi(&cp.cpu.m6800);
	} else if ((ctrl & OPENBUS_COPROC_IRQ_ASSERT) != 0) {
		(void) cpu6800_irq(&cp.cpu.m6800);
	}
}

