/* ------------------------------------------------- the Z80's port space */

/*
 * Port 0 is the mailbox; every other port is the latch inside the core, so a
 * program that only talks to itself still gets 255 working ports. See the
 * asymmetry note in openbus_coproc.h for why only the Z80 has this.
 */

static uint8_t
coproc_io_in(void *ctx, uint8_t port)
{
	(void) ctx;

	if (port == 0) {
		return (uint8_t) cp.mbox_tx;
	}
	return cp.cpu.z80.ports[port];
}

static void
coproc_io_out(void *ctx, uint8_t port, uint8_t val)
{
	(void) ctx;

	cp.cpu.z80.ports[port] = val;
	if (port == 0) {
		cp.mbox_rx = val;
	}
}

/* ------------------------------------------------------------- the aperture */

/**
 * Read @size bytes of card RAM at the aperture, advancing it.
 *
 * The advance is a side effect of a read, which is normally a thing to avoid -
 * but it is what makes the aperture worth having, and it is safe here for a
 * reason worth writing down: mem_phys_read8_debug() handles only ROM, VRAM and
 * RAM, so the debugger and the inspector cannot reach this window at all. There
 * is no way for a passive observer to disturb the aperture. See openbus.h.
 */
static uint32_t
aperture_read(openbus_size size)
{
	uint32_t val = 0;
	unsigned i;

	if (cp.ram == NULL || cp.ram_size == 0) {
		return 0xffffffffu;
	}

	for (i = 0; i < (unsigned) size; i++) {
		/* Wraps at the end of card RAM rather than faulting: the aperture
		   is a window a guest walks, and stopping dead at the top would
		   need an error path in every caller for no benefit. */
		val |= (uint32_t) cp.ram[(cp.addr + i) % cp.ram_size] << (i * 8);
	}
	cp.addr = (cp.addr + (uint32_t) size) % cp.ram_size;
	return val;
}

static void
aperture_write(openbus_size size, uint32_t val)
{
	unsigned i;

	if (cp.ram == NULL || cp.ram_size == 0) {
		return;
	}

	for (i = 0; i < (unsigned) size; i++) {
		cp.ram[(cp.addr + i) % cp.ram_size] = (uint8_t) (val >> (i * 8));
	}
	cp.addr = (cp.addr + (uint32_t) size) % cp.ram_size;
}

/*
 * The control area's aperture. The same shape as the card RAM one above and for
 * the same reason: a guest walks it with ordinary writes and needs no physical
 * address to do it.
 */
static uint32_t
ctl_aperture_read(openbus_size size)
{
	uint32_t val = 0;
	unsigned i;

	if (cp.ctl == NULL || cp.ctl_size == 0) {
		return 0xffffffffu;
	}

	for (i = 0; i < (unsigned) size; i++) {
		val |= (uint32_t) cp.ctl[(cp.ctl_addr + i) % cp.ctl_size] << (i * 8);
	}
	cp.ctl_addr = (cp.ctl_addr + (uint32_t) size) % cp.ctl_size;
	return val;
}

static void
ctl_aperture_write(openbus_size size, uint32_t val)
{
	unsigned i;

	if (cp.ctl == NULL || cp.ctl_size == 0) {
		return;
	}

	for (i = 0; i < (unsigned) size; i++) {
		cp.ctl[(cp.ctl_addr + i) % cp.ctl_size] = (uint8_t) (val >> (i * 8));
	}
	cp.ctl_addr = (cp.ctl_addr + (uint32_t) size) % cp.ctl_size;
}

/*
 * Hand the fitted core a hook onto the decode, or take it away again.
 *
 * Called whenever the map changes, because whether any region can stall decides
 * whether the core saves its registers before each instruction, and that is a
 * per-instruction cost nobody should pay for a map that cannot stall.
 */
/*
 * The card's own hook, wrapped round the decode's.
 *
 * ★ WHY IT IS NOT JUST THE DECODE'S HOOK. The Z80's port 0 is this card's
 * mailbox and its other ports are a latch inside the core, and both predate the
 * address map. Installing the decode's hook directly took them away, which broke
 * the mailbox the moment the map was introduced - caught by the card's own test
 * rather than by anything in the new code.
 *
 * So a port that no region describes still behaves as it always did, and a region
 * wins where one exists: a machine being emulated says what its ports are, and
 * anything it has not claimed is the card's.
 */
static cpu_mem_result
coproc_hook_read(void *ctx, uint32_t addr, uint8_t *value)
{
	const int is_port = (addr & CPU_MEM_PORT) != 0;
	const uint32_t bare = addr & ~CPU_MEM_PORT;

	if (is_port && copro_bus_region(&cp.bus, bare, 1) == NULL) {
		*value = coproc_io_in(ctx, (uint8_t) bare);
		return CPU_MEM_OK;
	}
	return cp.bus_hook.read(cp.bus_hook.ctx, addr, value);
}

static cpu_mem_result
coproc_hook_write(void *ctx, uint32_t addr, uint8_t value)
{
	const int is_port = (addr & CPU_MEM_PORT) != 0;
	const uint32_t bare = addr & ~CPU_MEM_PORT;

	if (is_port && copro_bus_region(&cp.bus, bare, 1) == NULL) {
		coproc_io_out(ctx, (uint8_t) bare, value);
		return CPU_MEM_OK;
	}
	return cp.bus_hook.write(cp.bus_hook.ctx, addr, value);
}

static void
coproc_rehook(void)
{
	cpu_mem_hook hook;

	copro_bus_hook(&cp.bus, &cp.bus_hook);
	hook.ctx = NULL;
	hook.read = coproc_hook_read;
	hook.write = coproc_hook_write;
	hook.can_stall = cp.bus_hook.can_stall;

	core_ops()->set_hook(&hook);
}

/* ------------------------------------------------------------------ the card */

static void
coproc_drop_irq(void)
{
	if (cp.irq) {
		cp.irq = 0;
		openbus_master_set_irq(0);
	}
}

static void
coproc_reset(void *p)
{
	(void) p;

	coproc_drop_irq();

	cp.ctrl = 0;
	cp.addr = 0;
	cp.mbox_tx = 0;
	cp.mbox_rx = 0;
	cp.stop_reported = 0;
	cp.dma_host = 0;
	cp.dma_local = 0;
	cp.dma_len = 0;
	cp.dma_to_host = 0;
	cp.dma_busy = 0;

	/* ENTRY survives, because a machine reset should not lose where the guest
	   said the program starts; the core is put back to that entry point. */
	core_reset();
}

static uint32_t
coproc_status(void)
{
	uint32_t val = 0;

	if ((cp.ctrl & OPENBUS_COPROC_CTRL_RUN) && !core_halted() && !core_faulted()) {
		val |= OPENBUS_COPROC_STATUS_RUNNING;
	}
	if (core_halted()) {
		val |= OPENBUS_COPROC_STATUS_HALTED;
	}
	if (core_faulted()) {
		val |= OPENBUS_COPROC_STATUS_FAULT;
	}
	if (cp.irq) {
		val |= OPENBUS_COPROC_STATUS_IRQ;
	}
	if (cp.dma_busy) {
		val |= OPENBUS_COPROC_STATUS_DMA;
	}
	if (core_stalled()) {
		/* Neither a fault nor a halt: the core is part way through an
		   instruction that the guest has to answer for. */
		val |= OPENBUS_COPROC_STATUS_WAITING;
	}
	return val;
}

/** Every register except DATA, which has its own path because it moves memory. */
static uint32_t
coproc_read_word(uint32_t reg)
{
	switch (reg) {
	case OPENBUS_COPROC_REG_ID:		return OPENBUS_COPROC_ID;
	case OPENBUS_COPROC_REG_CORE:		return core_id();
	case OPENBUS_COPROC_REG_RAMSIZE:	return cp.ram_size;
	case OPENBUS_COPROC_REG_CTRL:		return cp.ctrl;
	case OPENBUS_COPROC_REG_STATUS:		return coproc_status();
	case OPENBUS_COPROC_REG_ENTRY:		return cp.entry;
	case OPENBUS_COPROC_REG_ADDR:		return cp.addr;
	case OPENBUS_COPROC_REG_MBOX_TX:	return cp.mbox_tx;
	case OPENBUS_COPROC_REG_MBOX_RX:	return cp.mbox_rx;
	case OPENBUS_COPROC_REG_CYCLES:		return core_cycles();
	case OPENBUS_COPROC_REG_PC:		return core_pc();
	case OPENBUS_COPROC_REG_FAULT:
		/* Zero unless there is a fault, so that a guest reading FAULT
		   without checking STATUS first is not misled by the cause of an
		   older one. */
		return core_faulted() ? core_fault_cause() : 0;
	case OPENBUS_COPROC_REG_FAULTADDR:
		return core_faulted() ? core_fault_addr() : 0;
	case OPENBUS_COPROC_REG_DMAHOST:	return cp.dma_host;
	case OPENBUS_COPROC_REG_DMALOCAL:	return cp.dma_local;
	case OPENBUS_COPROC_REG_DMALEN:		return cp.dma_len;
	case OPENBUS_COPROC_REG_DMACTRL:
		return (uint32_t) ((cp.dma_busy ? OPENBUS_COPROC_DMA_START : 0) |
		                   (cp.dma_to_host ? OPENBUS_COPROC_DMA_TO_HOST : 0) |
		                   (cp.dma_control ? OPENBUS_COPROC_DMA_CONTROL : 0));
	case OPENBUS_COPROC_REG_RUNFOR:		return cp.runfor;
	case OPENBUS_COPROC_REG_STOPREASON:	return cp.stop_reason;
	case OPENBUS_COPROC_REG_IRQCTRL:	return cp.irqctrl;
	case OPENBUS_COPROC_REG_MAPOFF:		return cp.bus.map_off;
	case OPENBUS_COPROC_REG_MAPCOUNT:	return cp.bus.map_count;
	case OPENBUS_COPROC_REG_LOGOFF:		return cp.bus.log_off;
	case OPENBUS_COPROC_REG_LOGENTRIES:	return cp.bus.log_entries;
	case OPENBUS_COPROC_REG_LOGHEAD:	return cp.bus.log_head;
	case OPENBUS_COPROC_REG_LOGTAIL:	return cp.bus.log_tail;
	case OPENBUS_COPROC_REG_WAITADDR:	return cp.bus.wait_addr;
	case OPENBUS_COPROC_REG_WAITDATA:	return cp.bus.wait_value;
	case OPENBUS_COPROC_REG_WAITINFO:
		return (cp.bus.wait_is_write ? 1u : 0u) |
		       (cp.bus.wait_is_port ? 2u : 0u);
	case OPENBUS_COPROC_REG_CTLADDR:	return cp.ctl_addr;
	case OPENBUS_COPROC_REG_CTLSIZE:	return cp.ctl_size;
	case OPENBUS_COPROC_REG_REGSEL:		return cp.regsel;
	case OPENBUS_COPROC_REG_REGDATA:	return core_reg_read(cp.regsel);
	default:
		/* Nothing driving this address, including IRQCLEAR: it is write
		   only, and reading it would suggest otherwise. */
		return 0xffffffffu;
	}
}

/**
 * Note the core having stopped, once.
 *
 * Raising nPIRQ is what saves the guest from polling. It happens once per stop,
 * not once per timeslice, or the line would be re-asserted immediately after the
 * guest cleared it and the machine would spend its life in an interrupt handler.
 */
static void
coproc_note_stop(void)
{
	if (cp.stop_reported) {
		return;
	}
	if (!core_halted() && !core_faulted()) {
		return;
	}

	cp.stop_reported = 1;

	if (core_halted()) {
		cp.mbox_rx = core_exit_code();
	}

	/* RUN is cleared so that STATUS stops claiming the core is running and a
	   later timeslice does not try to execute a halted core. */
	cp.ctrl &= ~(uint32_t) OPENBUS_COPROC_CTRL_RUN;

	if (cp.ctrl & OPENBUS_COPROC_CTRL_IRQ_ON_HALT) {
		cp.irq = 1;
		openbus_master_set_irq(1);
	}
}

static void
coproc_start_dma(void)
{
	/* A transfer that would run outside card RAM does not start, and DMALEN
	   keeps its value so the guest can see that nothing happened. Clamping
	   instead would move somebody's data by an amount they did not ask for. */
	if (cp.ram == NULL || cp.dma_len == 0) {
		return;
	}
	if ((cp.dma_local & 3u) != 0) {
		return;		/* words, so the local address must be aligned */
	}
	/* The bound is checked before the subtraction that uses it, or an address
	   past the end of RAM would underflow and look like room to spare. */
	if (cp.dma_local >= cp.ram_size) {
		return;
	}
	if (cp.dma_len > (cp.ram_size - cp.dma_local) / 4u) {
		return;
	}

	cp.dma_busy = 1;
}

/**
 * Move the DMA on, as a bus master.
 *
 * @return cycles used, which the caller charges against the host's budget - so a
 *         transfer costs the guest real time rather than being free, exactly as
 *         the stub card's copy does.
 */
static int
coproc_run_dma(int budget)
{
	int used = 0;

	while (used < budget && cp.dma_len > 0) {
		int words = OPENBUS_COPROC_DMA_WORDS_PER_CYCLE;

		while (words-- > 0 && cp.dma_len > 0) {
			if (cp.dma_to_host) {
				const uint32_t word =
				    (uint32_t) cp.ram[cp.dma_local] |
				    ((uint32_t) cp.ram[cp.dma_local + 1] << 8) |
				    ((uint32_t) cp.ram[cp.dma_local + 2] << 16) |
				    ((uint32_t) cp.ram[cp.dma_local + 3] << 24);

				openbus_master_write32(cp.dma_host, word);
			} else {
				const uint32_t word = openbus_master_read32(cp.dma_host);

				cp.ram[cp.dma_local] = (uint8_t) word;
				cp.ram[cp.dma_local + 1] = (uint8_t) (word >> 8);
				cp.ram[cp.dma_local + 2] = (uint8_t) (word >> 16);
				cp.ram[cp.dma_local + 3] = (uint8_t) (word >> 24);
			}
			cp.dma_host += 4;
			cp.dma_local += 4;
			cp.dma_len--;
		}
		used++;
	}

	if (cp.dma_len == 0) {
		cp.dma_busy = 0;
	}
	return used;
}

static uint32_t
coproc_reg_read(void *p, uint32_t offset, openbus_size size)
{
	const uint32_t reg = offset & ~3u;
	const unsigned shift = (offset & 3u) * 8u;
	uint32_t word;

	(void) p;

	if (reg == OPENBUS_COPROC_REG_DATA) {
		return aperture_read(size);
	}
	if (reg == OPENBUS_COPROC_REG_CTLDATA) {
		return ctl_aperture_read(size);
	}

	word = coproc_read_word(reg);

	if (size == OPENBUS_SIZE_32) {
		return word;
	}

	/* A narrow access sees the addressed part of the word, little-endian, as
	   it would on the bus. The stub card answers the whole word whatever the
	   width; doing it properly here costs two lines and means a guest reading
	   the second byte of a register gets the second byte. */
	word >>= shift;
	return (size == OPENBUS_SIZE_8) ? (word & 0xffu) : (word & 0xffffu);
}

static void
coproc_reg_write(void *p, uint32_t offset, openbus_size size, uint32_t val)
{
	const uint32_t reg = offset & ~3u;

	(void) p;

	if (reg == OPENBUS_COPROC_REG_DATA) {
		aperture_write(size, val);
		return;
	}
	if (reg == OPENBUS_COPROC_REG_CTLDATA) {
		ctl_aperture_write(size, val);
		return;
	}
	(void) size;

	/*
	 * Narrow writes to the control registers are not merged into the word
	 * they address: every register here is a word, a guest driving this card
	 * writes words, and a byte write that quietly changed one quarter of
	 * CTRL would be a harder thing to explain than one that plainly writes
	 * the value given. The aperture above is the exception because its width
	 * is the point of it.
	 */

	switch (reg) {
	case OPENBUS_COPROC_REG_CTRL:
		/* RESET first and on its own: a write asking to reset and to run
		   in one go is a contradiction, and honouring the reset is the
		   less surprising reading. Self-clearing, so the bit never
		   sticks. */
		if (val & OPENBUS_COPROC_CTRL_RESET) {
			coproc_reset(NULL);
			return;
		}

		cp.ctrl = val & (OPENBUS_COPROC_CTRL_RUN |
		                 OPENBUS_COPROC_CTRL_IRQ_ON_HALT);

		/* Starting a core that has stopped arms the report again, so the
		   next halt raises nPIRQ as the first one did. */
		if ((cp.ctrl & OPENBUS_COPROC_CTRL_RUN) && !core_halted() &&
		    !core_faulted()) {
			cp.stop_reported = 0;
		}

		if (val & OPENBUS_COPROC_CTRL_STEP) {
			/* Executed here rather than on the next timeslice: a guest
			   that writes STEP and then reads PC expects the step to
			   have happened, and this write is already running on the
			   thread that owns the machine. */
			(void) core_step();
			coproc_note_stop();
		}
		break;

	case OPENBUS_COPROC_REG_ENTRY:
		cp.entry = val;
		break;

	case OPENBUS_COPROC_REG_RUNFOR:
		cp.runfor = val;
		break;

	case OPENBUS_COPROC_REG_IRQCTRL:
		cp.irqctrl = val;
		coproc_apply_interrupts();
		break;

	case OPENBUS_COPROC_REG_MAPOFF:
		/* Taken together with MAPCOUNT: an offset on its own describes
		   nothing, so the map is only re-pointed when the count is set. */
		cp.bus.map_off = val;
		break;

	case OPENBUS_COPROC_REG_MAPCOUNT:
		if (copro_bus_set_map(&cp.bus, cp.bus.map_off, val) == 0) {
			/* Refused, because it would not fit: the map in use is left
			   alone rather than half-applied. */
			break;
		}
		coproc_rehook();
		break;

	case OPENBUS_COPROC_REG_LOGOFF:
		cp.bus.log_off = val;
		break;

	case OPENBUS_COPROC_REG_LOGENTRIES:
		(void) copro_bus_set_log(&cp.bus, cp.bus.log_off, val);
		break;

	case OPENBUS_COPROC_REG_LOGTAIL:
		/* The guest says how far it has read. Anything past the head would
		   make the ring look full of entries that were never written. */
		if (cp.bus.log_entries != 0 && val < cp.bus.log_entries) {
			cp.bus.log_tail = val;
		}
		break;

	case OPENBUS_COPROC_REG_WAITDATA:
		cp.bus.wait_value = val;
		break;

	case OPENBUS_COPROC_REG_WAITACK:
		/* Answer the waiting access and let the core continue. The value
		   for a read is whatever was written to WAITDATA. */
		if (cp.bus.stalled) {
			(void) copro_bus_resume(&cp.bus, (uint8_t) cp.bus.wait_value);
			core_clear_stall();
		}
		break;

	case OPENBUS_COPROC_REG_CTLADDR:
		cp.ctl_addr = (cp.ctl_size != 0) ? (val % cp.ctl_size) : 0;
		break;

	case OPENBUS_COPROC_REG_REGSEL:
		cp.regsel = val;
		break;

	case OPENBUS_COPROC_REG_REGDATA:
		core_reg_write(cp.regsel, val);
		break;

	case OPENBUS_COPROC_REG_ADDR:
		cp.addr = (cp.ram_size != 0) ? (val % cp.ram_size) : 0;
		break;

	case OPENBUS_COPROC_REG_MBOX_TX:
		cp.mbox_tx = val;
		break;

	case OPENBUS_COPROC_REG_IRQCLEAR:
		coproc_drop_irq();
		break;

	case OPENBUS_COPROC_REG_DMAHOST:
		cp.dma_host = val;
		break;

	case OPENBUS_COPROC_REG_DMALOCAL:
		cp.dma_local = val;
		break;

	case OPENBUS_COPROC_REG_DMALEN:
		cp.dma_len = val;
		break;

	case OPENBUS_COPROC_REG_DMACTRL:
		cp.dma_to_host = (val & OPENBUS_COPROC_DMA_TO_HOST) != 0;
		if (val & OPENBUS_COPROC_DMA_START) {
			coproc_start_dma();
		}
		break;

	default:
		/* Read-only or unimplemented. Dropped, as an undriven write is. */
		break;
	}
}

static int
coproc_run(void *p, int cycles)
{
	int used = 0;

	(void) p;

	if (cycles <= 0) {
		return 0;
	}

	/* The transfer goes first: a program waiting for its data cannot make
	   progress until the data is there, and the card is one bus master
	   whichever of the two is using it. */
	if (cp.dma_busy) {
		used += coproc_run_dma(cycles);
	}

	if ((cp.ctrl & OPENBUS_COPROC_CTRL_RUN) && used < cycles) {
		int budget = cycles - used;
		int ran;

		/*
		 * RUNFOR is what lets a guest emulate a machine a frame at a time:
		 * ask for 69888 cycles and a Spectrum frame is what comes back,
		 * however many timeslices the card is given to do it in. Zero means
		 * no limit, which is what the card did before this existed.
		 */
		if (cp.runfor != 0 && (uint32_t) budget > cp.runfor) {
			budget = (int) cp.runfor;
		}

		ran = core_run(budget);
		used += ran;

		if (cp.runfor != 0) {
			/*
			 * Floored, not subtracted: an instruction is indivisible, so
			 * a core asked for the last 2 cycles of a budget may take 4
			 * and overshoot. Subtracting would wrap the count and the
			 * budget would never reach zero - the core then ran until it
			 * halted, which is exactly what the register exists to
			 * prevent, and the test caught it.
			 */
			cp.runfor = ((uint32_t) ran >= cp.runfor)
			    ? 0 : cp.runfor - (uint32_t) ran;
			if (cp.runfor == 0) {
				/* Budget spent: stop, and leave it to the guest to
				   give another. RUN is cleared so a later timeslice
				   does not carry on past the frame it asked for. */
				cp.ctrl &= ~(uint32_t) OPENBUS_COPROC_CTRL_RUN;
				cp.stop_reason = OPENBUS_COPROC_STOP_BUDGET;
			}
		}

		if (core_faulted()) {
			cp.stop_reason = OPENBUS_COPROC_STOP_FAULT;
		} else if (core_halted()) {
			cp.stop_reason = OPENBUS_COPROC_STOP_HALTED;
		} else if (core_stalled()) {
			/* RUN stays set: answering the access is all that is needed
			   for the core to carry on where it was. */
			cp.stop_reason = OPENBUS_COPROC_STOP_WAITING;
		}

		coproc_note_stop();
	} else if ((cp.ctrl & OPENBUS_COPROC_CTRL_RUN) == 0 &&
	           cp.stop_reason == OPENBUS_COPROC_STOP_NONE) {
		cp.stop_reason = OPENBUS_COPROC_STOP_STOPPED;
	}

	return used;
}

static void
coproc_close(void *p)
{
	(void) p;

	free(cp.ram);
	cp.ram = NULL;
	cp.ram_size = 0;
	free(cp.ctl);
	cp.ctl = NULL;
	cp.ctl_size = 0;
}

