#define COPROC_CORE_COUNT ((int) (sizeof(coproc_cores) / sizeof(coproc_cores[0])))

/* The row for the fitted core, or the first one if nothing sensible is set: a
   NULL here would be a crash rather than a wrong answer, and neither is wanted
   in a register read. */
static const coproc_core_ops *
core_ops(void)
{
	if ((int) cp.core < 0 || (int) cp.core >= COPROC_CORE_COUNT) {
		return &coproc_cores[0];
	}
	return &coproc_cores[cp.core];
}

/*
 * Hand the fitted core whatever IRQCTRL is asking for. Level-triggered as the
 * hardware is for the maskable line: while the bit is set the interrupt is
 * offered, and the guest clears it when its device would stop asserting.
 */
static void
coproc_apply_interrupts(void)
{
	const uint32_t ctrl = cp.irqctrl;

	core_ops()->interrupt(ctrl);

	/* The non-maskable one is edge triggered on the way in, or it would be
	   taken again on every register write. */
	if ((ctrl & OPENBUS_COPROC_IRQ_NMI) != 0) {
		cp.irqctrl &= ~(uint32_t) OPENBUS_COPROC_IRQ_NMI;
	}
}

