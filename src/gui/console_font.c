/*
 * console_font.c - an 8x16 bitmap font, so the emulator can draw text itself.
 *
 * The emulator has never rendered a character of its own: the interface is
 * wxWidgets and the guest draws its own screen. Anything shown to a VNC client
 * before a machine exists has nowhere to come from, so it needs a font of its
 * own, and one that is a fixed cell rather than a proportional face, because the
 * things drawn with it are lists and columns.
 *
 * Provenance. This is the printable ASCII range of the 8x16 console font shipped
 * as Lat15-Fixed16 in the kbd package, whose copyright file states GPL-2+; the
 * family descends from the X11 misc-fixed fonts. GPL-2+ is compatible with this
 * program's GPL-2-or-later, so it is included directly rather than loaded at run
 * time, which would mean a file to find, a format to parse and a failure path to
 * handle for something that is 1520 bytes.
 *
 * Generated, not typed. Each glyph is 16 bytes, one per row, bit 7 leftmost.
 * Index 0 is space (32); the table ends at tilde (126). Anything outside that
 * range is drawn as a full stop by the renderer rather than indexing past the
 * end.
 */

